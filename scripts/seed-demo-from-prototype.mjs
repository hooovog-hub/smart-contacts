// Generates supabase/seed_demo.sql from the prototype's demo data (P, ORGS, EXTRA, BIOS, MEETINGS).
// Usage: node scripts/seed-demo-from-prototype.mjs <owner_profile_uuid> > supabase/seed_demo.sql
// Everything it creates is marked is_demo = true (profiles, contacts). Remove with supabase/remove_demo.sql.
// IDs are deterministic: md5('scd:' || key)::uuid, so the seed can be re-run safely.
import { readFileSync } from "node:fs";
import vm from "node:vm";

const OWNER = process.argv[2];
if (!/^[0-9a-f-]{36}$/.test(OWNER ?? "")) throw new Error("owner uuid required");

const html = readFileSync(new URL("../prototype/smart-contacts-prototype.html", import.meta.url), "utf8");
const src = html.slice(html.indexOf("const P = ["), html.indexOf("/* ---------- state ---------- */"));
const ctx = {};
vm.runInNewContext(src.replace(/\bconst (P|MEETINGS)\b/g, "globalThis.$1").replace(/^const /gm, "var "), ctx);
const { P, MEETINGS } = ctx;

const TR = { а:"a",б:"b",в:"v",г:"g",д:"d",е:"e",ё:"e",ж:"zh",з:"z",и:"i",й:"y",к:"k",л:"l",м:"m",н:"n",о:"o",п:"p",р:"r",с:"s",т:"t",у:"u",ф:"f",х:"kh",ц:"ts",ч:"ch",ш:"sh",щ:"sh",ъ:"",ы:"y",ь:"",э:"e",ю:"yu",я:"ya" };
const handle = (n) => n.toLowerCase().split("").map((ch) => TR[ch] ?? ch).join("").replace(/[^a-z0-9]+/g, ".").replace(/^\.|\.$/g, "").slice(0, 30);
const clean = (o) => Object.fromEntries(Object.entries(o ?? {}).filter(([, v]) => v !== "" && v != null));

const pro = P.filter((p) => !p.basic);
const D = { orgs: [], profiles: [], brands: [], members: [], awards: [], endorse: [], rooms: [], rm: [], contacts: [] };
const orgs = new Map();
for (const p of P) for (const o of p.orgs ?? []) orgs.set(o.n, { n: o.n, k: /клуб/i.test(o.n) ? "club" : /палат/i.test(o.n) ? "chamber" : "association", v: !!o.v });
D.orgs = [...orgs.values()];
for (const p of pro) {
  D.profiles.push(clean({ k: p.id, h: handle(p.name), n: p.name, r: p.role, b: p.bio, c: p.city ?? "Ереван", lg: p.langs ?? [], ph: p.phone,
    l: clean({ ...(p.links ?? {}), telegram: p.tg }), he: p.helps ?? [], se: p.seeks ?? [], pl: p.pro ? "pro" : "free" }));
  (p.biz ?? []).forEach((b, i) => { if (b.name && !/^(Фриланс|Частная практика|Частное производство)$/.test(b.name)) D.brands.push(clean({ k: p.id, i, n: b.name, s: b.sphere, d: b.desc, y: b.year ? Number(b.year) : null, t: b.team, o: b.offer, l: b.links ?? {} })); });
  (p.orgs ?? []).forEach((o, i) => D.members.push(clean({ k: p.id, i, n: o.n, r: o.r, y: o.y, v: !!o.v })));
  (p.awards ?? []).forEach((a, i) => D.awards.push(clean({ k: p.id, i, t: a.t, kd: a.k, y: a.y, s: a.src })));
  for (const e of p.endorse ?? []) if (pro.some((x) => x.id === e.from) && e.from !== p.id) D.endorse.push({ f: e.from, t: p.id, x: e.text });
}
const roomOwner = { m1: "p15", m2: "p11", m3: null, m0: "p11" };
const times = { m1: "09:00", m2: "10:00", m3: "13:30", m0: "19:30" };
const metIn = {};
for (const m of MEETINGS) {
  D.rooms.push(clean({ k: m.id, o: roomOwner[m.id], t: m.title, kd: m.kind, p: m.place, at: `${m.date} ${times[m.id]}+04`, c: m.code.replace("-", "") }));
  [...m.people, "me"].forEach((p, i) => D.rm.push({ r: m.id, p, i }));
  if (!m.upcoming) for (const p of m.people) metIn[p] ??= m;
}
const notes = { p15: "Хозяин кофейни, предложил зал для нашего воркшопа" };
for (const p of P) {
  const m = metIn[p.id];
  D.contacts.push(clean({ k: p.id, linked: !p.basic, n: p.name, ph: p.phone, r: p.basic ? p.role : [p.role, p.biz?.[0]?.name].filter((x) => x && !/^(Фриланс|Частная практика|Частное производство)$/.test(x)).join(", "),
    c: p.cat === "mant" ? "mantashyants" : p.cat, nt: notes[p.id], m: m?.id, at: m ? `${m.date} 12:00+04` : null }));
}

const J = (x) => `'${JSON.stringify(x).replace(/'/g, "''")}'::jsonb`;
const id = (expr) => `md5('scd:'||${expr})::uuid`;
const sql = `-- Generated by scripts/seed-demo-from-prototype.mjs. Demo data only.
begin;
insert into organizations(name,kind,verified) select n,k,v from jsonb_to_recordset(${J(D.orgs)}) x(n text,k text,v boolean) on conflict (name) do nothing;
insert into auth.users(instance_id,id,aud,role,email,encrypted_password,raw_app_meta_data,raw_user_meta_data,created_at,updated_at)
 select '00000000-0000-0000-0000-000000000000',${id("'profile:'||k")},'authenticated','authenticated',h||'@demo.smartcontacts.invalid',extensions.crypt(gen_random_uuid()::text,extensions.gen_salt('bf')),'{"provider":"email","providers":["email"]}','{"demo":true}',now(),now()
 from jsonb_to_recordset(${J(D.profiles.map(({ k, h }) => ({ k, h })))}) x(k text,h text) on conflict (id) do nothing;
insert into profiles(id,handle,full_name,role,bio,city,languages,phone,links,helps,seeks,plan,is_demo)
 select ${id("'profile:'||k")},h,n,r,b,c,lg,ph,coalesce(l,'{}'),coalesce(he,'{}'),coalesce(se,'{}'),pl::plan,true
 from jsonb_to_recordset(${J(D.profiles)}) x(k text,h text,n text,r text,b text,c text,lg text[],ph text,l jsonb,he text[],se text[],pl text) on conflict (id) do nothing;
insert into brands(id,profile_id,name,sphere,description,founded_year,team_size,offer,links,position)
 select ${id("'brand:'||k||':'||i")},${id("'profile:'||k")},n,s,d,y,t,o,coalesce(l,'{}'),i
 from jsonb_to_recordset(${J(D.brands)}) x(k text,i int,n text,s text,d text,y int,t text,o text,l jsonb) on conflict (id) do nothing;
insert into memberships(id,profile_id,organization_id,org_name,status_title,since_year,verified)
 select ${id("'mem:'||k||':'||i")},${id("'profile:'||k")},(select o.id from organizations o where o.name=x.n),n,r,y,v
 from jsonb_to_recordset(${J(D.members)}) x(k text,i int,n text,r text,y int,v boolean) on conflict (id) do nothing;
insert into awards(id,profile_id,title,kind,year,source)
 select ${id("'award:'||k||':'||i")},${id("'profile:'||k")},t,kd::award_kind,y,s
 from jsonb_to_recordset(${J(D.awards)}) x(k text,i int,t text,kd text,y int,s text) on conflict (id) do nothing;
insert into endorsements(from_profile,to_profile,text)
 select ${id("'profile:'||f")},${id("'profile:'||t")},x from jsonb_to_recordset(${J(D.endorse)}) j(f text,t text,x text) on conflict do nothing;
insert into categories(owner_id,key,name,color,position,is_system) values ('${OWNER}','mantashyants','Бизнес-клуб «Манташянц»','#A57CFF',20,false) on conflict (owner_id,key) do nothing;
insert into rooms(id,owner_id,title,kind,place,starts_at,code)
 select ${id("'room:'||k")},coalesce(${id("'profile:'||o")},'${OWNER}'),t,kd,p,at::timestamptz,c
 from jsonb_to_recordset(${J(D.rooms)}) x(k text,o text,t text,kd text,p text,at text,c text) on conflict (id) do nothing;
insert into room_members(id,room_id,profile_id,joined_at)
 select ${id("'rm:'||r||':'||p")},${id("'room:'||r")},case when p='me' then '${OWNER}'::uuid else ${id("'profile:'||p")} end,(select starts_at from rooms where id=${id("'room:'||r")})+make_interval(mins=>i*3)
 from jsonb_to_recordset(${J(D.rm)}) x(r text,p text,i int) on conflict (id) do nothing;
insert into meeting_marks(owner_id,member_id,talked) values ('${OWNER}',${id("'rm:m1:p15'")},true),('${OWNER}',${id("'rm:m1:p2'")},true) on conflict do nothing;
insert into contacts(id,owner_id,linked_profile_id,display_name,phone,role,category_key,note,source,met_room_id,met_at,category_locked,is_demo)
 select ${id("'contact:'||k")},'${OWNER}',case when linked then ${id("'profile:'||k")} end,n,ph,r,c,nt,(case when m is null then 'manual' else 'room' end)::contact_source,${id("'room:'||m")},at::timestamptz,true,true
 from jsonb_to_recordset(${J(D.contacts)}) x(k text,linked boolean,n text,ph text,r text,c text,nt text,m text,at text) on conflict (id) do nothing;
commit;
`;
process.stdout.write(sql);
